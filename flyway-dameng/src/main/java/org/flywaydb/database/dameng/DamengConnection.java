package org.flywaydb.database.dameng;

import org.flywaydb.core.internal.database.base.Connection;
import java.sql.SQLException;

public class DamengConnection extends Connection<DamengDatabase> {
    public DamengConnection(DamengDatabase database, java.sql.Connection connection) {
        super(database, connection);
    }

    @Override
    protected String getCurrentSchemaNameOrSearchPath() throws SQLException {
        return jdbcTemplate.queryForString("SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') FROM DUAL");
    }

    @Override
    public void doChangeCurrentSchemaOrSearchPathTo(String schema) throws SQLException {
        jdbcTemplate.execute("SET SCHEMA " + database.quote(schema));
    }

    @Override
    public DamengSchema getSchema(String name) {
        return new DamengSchema(jdbcTemplate, database, name);
    }
}
